import { Competition, TournamentStatus } from '@/types';

export function computeStatus(startDateStr: string, endDateStr: string): TournamentStatus {
  const now = new Date();
  const start = new Date(startDateStr);
  const end = new Date(endDateStr);

  if (now < start) return 'upcoming';
  if (now > end) return 'ended';
  return 'live';
}

